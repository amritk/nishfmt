/** One file's CSharp state; a fresh one formats each file, in a region of its own. */
export class CSharpEngine {
  debug: boolean = false;
  constructor() {}
}

const csLower = (c: i32): i32 => (c >= 65 && c <= 90 ? c + 32 : c);

const csEndsWithIgnoreCase = (s: string, a: i32, b: i32, w: string): boolean => {
  const m = toI32(w.length);
  if (b - a < m) {
    return false;
  }
  for (let i = 0; i < m; i++) {
    if (csLower(s.charCodeAt(b - m + i)) !== csLower(w.charCodeAt(i))) {
      return false;
    }
  }
  return true;
};

/** GeneratedCodeUtilities.IsGeneratedCodeFile. */
const csIsGeneratedFile = (path: string): boolean => {
  let s = 0;
  const n = toI32(path.length);
  for (let i = 0; i < n; i++) {
    const c = path.charCodeAt(i);
    if (c === 47 || c === 92) {
      s = i + 1;
    }
  }
  const w = "TemporaryGeneratedFile_";
  if (n - s >= toI32(w.length)) {
    let ok = true;
    for (let i = 0; i < toI32(w.length); i++) {
      if (csLower(path.charCodeAt(s + i)) !== csLower(w.charCodeAt(i))) {
        ok = false;
        break;
      }
    }
    if (ok) {
      return true;
    }
  }
  // the extension
  let dot = -1;
  for (let i = n - 1; i >= s; i--) {
    if (path.charCodeAt(i) === 46) {
      dot = i;
      break;
    }
  }
  if (dot < 0 || dot === n - 1) {
    return false;
  }
  return (
    csEndsWithIgnoreCase(path, s, dot, ".designer") ||
    csEndsWithIgnoreCase(path, s, dot, ".generated") ||
    csEndsWithIgnoreCase(path, s, dot, ".g") ||
    csEndsWithIgnoreCase(path, s, dot, ".g.i")
  );
};

/** BeginsWithAutoGeneratedComment: a comment in the first token's leading trivia mentions <autogenerated or <auto-generated. */
const csBeginsWithAutoGenerated = (lx: CsLexer): boolean => {
  if (lx.nt === 0) {
    return false;
  }
  const src = lx.src;
  for (let i = lx.l0[0]; i < lx.l1[0]; i++) {
    const k = lx.trKind[i];
    if (k !== K_SingleLineCommentTrivia && k !== K_MultiLineCommentTrivia) {
      continue;
    }
    const a = lx.trStart[i];
    const b = lx.trTextEnd[i];
    for (let j = a; j < b; j++) {
      if (toI32(src[j]) !== 60) {
        continue;
      }
      if (csMatchAt(src, j, b, "<autogenerated") || csMatchAt(src, j, b, "<auto-generated")) {
        return true;
      }
    }
  }
  return false;
};

const csMatchAt = (src: u8[], j: i32, b: i32, w: string): boolean => {
  const m = toI32(w.length);
  if (b - j < m) {
    return false;
  }
  for (let i = 0; i < m; i++) {
    if (toI32(src[j + i]) !== w.charCodeAt(i)) {
      return false;
    }
  }
  return true;
};

class CsParsed {
  lx: CsLexer;
  t: CsTree | null;
  root: i32;
  err: string;
  constructor(lx: CsLexer, t: CsTree | null, root: i32, err: string) {
    this.lx = lx;
    this.t = t;
    this.root = root;
    this.err = err;
  }
}

const csParse = (src: u8[], a: i32, b: i32, syms: string[]): CsParsed => {
  const copy: string[] = [];
  for (let i = 0; i < toI32(syms.length); i++) {
    copy.push(syms[i]);
  }
  const lx = new CsLexer(src, a, b, copy);
  lx.lexFile();
  if (lx.err) {
    return new CsParsed(lx, null, -1, `lex: ${lx.errMsg}`);
  }
  const p = new CsParser(lx);
  const root = cspCompilationUnit(p);
  if (p.err || root < 0) {
    return new CsParsed(lx, null, -1, `parse: ${p.errMsg}`);
  }
  return new CsParsed(lx, p.t, root, "");
};

/** Prints a parsed file into out; answers an error message, or "" when it printed. */
const csPrintTree = (lx: CsLexer, root: i32, tree: CsTree, eolCr: boolean, out: Out): string => {
  const D = new CsDocs(lx.src, lx.nt * 4 + 64);
  const P = new CsPrint(tree, D, eolCr);
  const doc = cswNode(P, root);
  if (P.failed) {
    return P.failMsg;
  }
  out.n = 0;
  const pr = new CsPrinter(D, out, 100, 4, false, eolCr);
  pr.print(doc);
  return "";
};

/** Formats `src[0, n)` into `out` as CSharpier does; answers false when the file cannot be formatted. */
export const formatCSharp = (e: CSharpEngine, path: string, src: u8[], n: i32, out: Out): boolean => {
  out.n = 0;
  if (csIsGeneratedFile(path)) {
    if (e.debug) {
      console.error(`${path}: a generated file`);
    }
    return false;
  }
  let s = 0;
  if (n >= 3 && toI32(src[0]) === 0xef && toI32(src[1]) === 0xbb && toI32(src[2]) === 0xbf) {
    s = 3;
  }
  const none: string[] = [];
  const first = csParse(src, s, n, none);
  if (first.root < 0) {
    if (e.debug) {
      console.error(`${path}: ${first.err}`);
    }
    return false;
  }
  const lx = first.lx;
  if (csBeginsWithAutoGenerated(lx)) {
    if (e.debug) {
      console.error(`${path}: an auto-generated file`);
    }
    return false;
  }
  // the line ending: the first line break's
  let eolCr = false;
  for (let i = s; i < n; i++) {
    if (toI32(src[i]) === 10) {
      eolCr = i > s && toI32(src[i - 1]) === 13;
      break;
    }
  }
  const tree = first.t;
  if (tree === null) {
    return false;
  }
  const body = new Out(n + 1024);
  const msg = csPrintTree(lx, first.root, tree, eolCr, body);
  if (msg !== "") {
    if (e.debug) {
      console.error(`${path}: ${msg}`);
    }
    return false;
  }
  const sets = csSymbolSets(lx);
  if (sets.failed) {
    if (e.debug) {
      console.error(`${path}: a preprocessor condition CSharpier cannot parse`);
    }
    return false;
  }
  let cur = body;
  const passes = e.debug && getenv("FFCS_NOSYMS") !== null ? 0 : toI32(sets.sets.length);
  for (let si = 0; si < passes; si++) {
    const code = new Array<u8>(cur.n);
    for (let i = 0; i < cur.n; i++) {
      code[i] = cur.buf[i];
    }
    const again = csParse(code, 0, cur.n, sets.sets[si]);
    if (again.root < 0) {
      if (e.debug) {
        console.error(`${path}: with ${sets.keys[si]}: ${again.err}`);
      }
      return false;
    }
    const next = new Out(cur.n + 1024);
    const at = again.t;
    if (at === null) {
      return false;
    }
    const m2 = csPrintTree(again.lx, again.root, at, eolCr, next);
    if (m2 !== "") {
      if (e.debug) {
        console.error(`${path}: with ${sets.keys[si]}: ${m2}`);
      }
      return false;
    }
    cur = next;
  }
  out.n = 0;
  if (s === 3) {
    out.byte(0xef);
    out.byte(0xbb);
    out.byte(0xbf);
  }
  out.range(cur.buf, 0, cur.n);
  return true;
};


export const isCSharpName = (name: string): boolean => name.endsWith(".cs");
