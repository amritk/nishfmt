/** One file's CSharp state; a fresh one formats each file, in a region of its own. */
export class CSharpEngine {
  debug: boolean = false;
  constructor() {}
}

const csLower = (c: i32): i32 => (c >= 65 && c <= 90 ? c + 32 : c);

/** Whether `s` ends with `w`, ignoring ASCII case. */
const csEndsWithIgnoreCase = (s: string, w: string): boolean => {
  const n = toI32(s.length);
  const m = toI32(w.length);
  if (n < m) {
    return false;
  }
  let j = n - m;
  for (let i = 0; i < m && j >= 0 && j < s.length; i++) {
    if (csLower(s.charCodeAt(j)) !== csLower(w.charCodeAt(i))) {
      return false;
    }
    j++;
  }
  return true;
};

/** GeneratedCodeUtilities.IsGeneratedCodeFile. */
const csIsGeneratedFile = (path: string): boolean => {
  let s = 0;
  const pn = toI32(path.length);
  for (let i = 0; i < pn; i++) {
    const c = path.charCodeAt(i);
    if (c === 47 || c === 92) {
      s = i + 1;
    }
  }
  // the file name, after the last separator
  const name = path.substring(s, pn);
  const n = toI32(name.length);
  const w = "TemporaryGeneratedFile_";
  if (n >= toI32(w.length)) {
    let ok = true;
    for (let i = 0; i < toI32(w.length) && i < n; i++) {
      if (csLower(name.charCodeAt(i)) !== csLower(w.charCodeAt(i))) {
        ok = false;
        break;
      }
    }
    if (ok) {
      return true;
    }
  }
  // the extension
  let dot = -1;
  for (let i = n - 1; i >= 0 && i < n; i--) {
    if (name.charCodeAt(i) === 46) {
      dot = i;
      break;
    }
  }
  if (dot < 0 || dot === n - 1) {
    return false;
  }
  const stem = name.substring(0, dot);
  return (
    csEndsWithIgnoreCase(stem, ".designer") ||
    csEndsWithIgnoreCase(stem, ".generated") ||
    csEndsWithIgnoreCase(stem, ".g") ||
    csEndsWithIgnoreCase(stem, ".g.i")
  );
};

/** BeginsWithAutoGeneratedComment: a comment in the first token's leading trivia mentions <autogenerated or <auto-generated. */
const csBeginsWithAutoGenerated = (lx: CsLexer): boolean => {
  if (lx.nt === 0) {
    return false;
  }
  const src = lx.src;
  const l0 = lx.l0;
  const l1 = lx.l1;
  if (l0.length < 1 || l1.length < 1) {
    fault();
    return false;
  }
  const i0 = l0[0];
  const i1 = l1[0];
  const trKind = lx.trKind;
  const trStart = lx.trStart;
  const trTextEnd = lx.trTextEnd;
  for (let i = i0; i < i1; i++) {
    // the token's trivia indices are inside the trivia arrays
    if (i < 0 || i >= trKind.length || i >= trStart.length || i >= trTextEnd.length) {
      fault();
      return false;
    }
    const k = trKind[i];
    if (k !== K_SingleLineCommentTrivia && k !== K_MultiLineCommentTrivia) {
      continue;
    }
    const a = trStart[i];
    const b = trTextEnd[i];
    for (let j = a; j < b; j++) {
      if (j < 0 || j >= src.length) {
        fault();
        return false;
      }
      if (toI32(src[j]) !== 60) {
        continue;
      }
      if (csMatchAt(src, j, b, "<autogenerated") || csMatchAt(src, j, b, "<auto-generated")) {
        return true;
      }
    }
  }
  return false;
};

const csMatchAt = (src: u8[], j: i32, b: i32, w: string): boolean => {
  const m = toI32(w.length);
  if (toI64(b) - toI64(j) < toI64(m)) {
    return false;
  }
  let k = j;
  for (let i = 0; i < m; i++) {
    if (k < 0 || k >= src.length) {
      fault();
      return false;
    }
    if (toI32(src[k]) !== w.charCodeAt(i)) {
      return false;
    }
    k++;
  }
  return true;
};

class CsParsed {
  lx: CsLexer;
  t: CsTree | null;
  root: i32;
  err: string;
  constructor(lx: CsLexer, t: CsTree | null, root: i32, err: string) {
    this.lx = lx;
    this.t = t;
    this.root = root;
    this.err = err;
  }
}

const csParse = (src: u8[], a: i32, b: i32, syms: string[]): CsParsed => {
  const copy: string[] = [];
  for (let i = 0; i < toI32(syms.length); i++) {
    copy.push(syms[i]);
  }
  const lx = new CsLexer(src, a, b, copy);
  lx.lexFile();
  if (lx.err) {
    return new CsParsed(lx, null, -1, `lex: ${lx.errMsg}`);
  }
  const p = new CsParser(lx);
  const root = cspCompilationUnit(p);
  if (p.err || root < 0) {
    return new CsParsed(lx, null, -1, `parse: ${p.errMsg}`);
  }
  return new CsParsed(lx, p.t, root, "");
};

/** Prints a parsed file into out; answers an error message, or "" when it printed. */
const csPrintTree = (lx: CsLexer, root: i32, tree: CsTree, out: Out): string => {
  // PrinterOptions.GetLineEnding: the style's end_of_line = crlf gives "\r\n",
  // whatever the input's line breaks are
  const eolCr = true;
  const nt = lx.nt;
  // a token count, far below the bound
  if (nt < 0 || nt > 715827861) {
    fault();
    return "too many tokens";
  }
  const D = new CsDocs(lx.src, nt * 3 + 64);
  const P = new CsPrint(tree, D, eolCr);
  const doc = cswNode(P, root);
  if (P.failed) {
    return P.failMsg;
  }
  out.n = 0;
  const pr = new CsPrinter(D, out, 100, 4, false, eolCr);
  pr.print(doc);
  return "";
};

/** The name of symbol set `si`, for a debug message. */
const csSetKey = (keys: string[], si: i32): string => {
  if (si >= 0 && si < keys.length) {
    return keys[si];
  }
  fault();
  return "";
};

/** Formats `src[0, n)` into `out` as CSharpier does; answers false when the file cannot be formatted. */
export const formatCSharp = (e: CSharpEngine, path: string, src: u8[], n: i32, out: Out): boolean => {
  out.n = 0;
  if (csIsGeneratedFile(path)) {
    if (e.debug) {
      console.error(`${path}: a generated file`);
    }
    return false;
  }
  let s = 0;
  if (n >= 3) {
    // n is at most the buffer's length
    if (src.length < 3) {
      fault();
      return false;
    }
    if (toI32(src[0]) === 0xef && toI32(src[1]) === 0xbb && toI32(src[2]) === 0xbf) {
      s = 3;
    }
  }
  const none: string[] = [];
  const first = csParse(src, s, n, none);
  if (first.root < 0) {
    if (e.debug) {
      console.error(`${path}: ${first.err}`);
    }
    return false;
  }
  const lx = first.lx;
  if (csBeginsWithAutoGenerated(lx)) {
    if (e.debug) {
      console.error(`${path}: an auto-generated file`);
    }
    return false;
  }
  const tree = first.t;
  if (tree === null) {
    return false;
  }
  if (n > 2147482623) {
    fault();
    return false;
  }
  const body = new Out(n + 1024);
  const msg = csPrintTree(lx, first.root, tree, body);
  if (msg !== "") {
    if (e.debug) {
      console.error(`${path}: ${msg}`);
    }
    return false;
  }
  const sets = csSymbolSets(lx);
  if (sets.failed) {
    if (e.debug) {
      console.error(`${path}: a preprocessor condition CSharpier cannot parse`);
    }
    return false;
  }
  let cur = body;
  const passes = e.debug && getenv("FFCS_NOSYMS") !== null ? 0 : toI32(sets.sets.length);
  const symSets = sets.sets;
  for (let si = 0; si < passes && si < symSets.length; si++) {
    const syms = symSets[si];
    const cn = cur.n;
    const code = sliceU8s(cur.buf, 0, cn);
    const again = csParse(code, 0, cn, syms);
    if (again.root < 0) {
      if (e.debug) {
        console.error(`${path}: with ${csSetKey(sets.keys, si)}: ${again.err}`);
      }
      return false;
    }
    if (cn > 2147482623) {
      fault();
      return false;
    }
    const next = new Out(cn + 1024);
    const at = again.t;
    if (at === null) {
      return false;
    }
    const m2 = csPrintTree(again.lx, again.root, at, next);
    if (m2 !== "") {
      if (e.debug) {
        console.error(`${path}: with ${csSetKey(sets.keys, si)}: ${m2}`);
      }
      return false;
    }
    cur = next;
  }
  out.n = 0;
  if (s === 3) {
    out.byte(0xef);
    out.byte(0xbb);
    out.byte(0xbf);
  }
  out.range(cur.buf, 0, cur.n);
  return true;
};

export const isCSharpName = (name: string): boolean => name.endsWith(".cs");
