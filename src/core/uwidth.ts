/** The `k`-th six-hex-digit number of table `t`. */
const entry = (t: string, k: i32): i32 => {
  let v = 0;
  for (let i = k * 6; i < k * 6 + 6; i++) {
    const c = t.charCodeAt(i);
    v = v * 16 + (c <= 57 ? c - 48 : c - 87);
  }
  return v;
};

/** Whether `cp` falls in one of the sorted [first, last] pairs of `t`. */
const inRanges = (t: string, cp: i32): boolean => {
  let lo = 0;
  let hi = toI32(t.length) / 12 - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (cp < entry(t, mid * 2)) {
      hi = mid - 1;
    } else if (cp > entry(t, mid * 2 + 1)) {
      lo = mid + 1;
    } else {
      return true;
    }
  }
  return false;
};

/** Columns code point `cp` takes: 0, 1 or 2, or -1 when it is not printable. */
export const cpWidth = (cp: i32): i32 => {
  if (cp !== 0xad && !inRanges(PRINTABLE, cp)) {
    return -1;
  }
  if (inRanges(COMBINING, cp)) {
    return 0;
  }
  return inRanges(WIDE, cp) ? 2 : 1;
};

/**
 * Columns the UTF-8 bytes [a, b) of `src` take (no tabs among them), as
 * clang-format's columnWidth counts them: their byte count when one is not
 * printable or the bytes are not valid UTF-8.
 */
export const utf8Width = (src: u8[], a: i32, b: i32): i32 => {
  let w = 0;
  let i = a;
  while (i < b) {
    const c = toI32(uncheckedGet(src, i));
    if (c < 128) {
      if (c < 32 || c === 127) {
        return b - a;
      }
      w++;
      i++;
      continue;
    }
    let n = 0;
    let cp = 0;
    if (c >= 0xf0 && c < 0xf8) {
      n = 4;
      cp = c & 7;
    } else if (c >= 0xe0) {
      n = 3;
      cp = c & 15;
    } else if (c >= 0xc0) {
      n = 2;
      cp = c & 31;
    } else {
      return b - a;
    }
    if (i + n > b) {
      return b - a;
    }
    for (let k = 1; k < n; k++) {
      const cc = toI32(uncheckedGet(src, i + k));
      if ((cc & 0xc0) !== 0x80) {
        return b - a;
      }
      cp = (cp << 6) | (cc & 63);
    }
    const cw = cpWidth(cp);
    if (cw < 0) {
      return b - a;
    }
    w = w + cw;
    i = i + n;
  }
  return w;
};
