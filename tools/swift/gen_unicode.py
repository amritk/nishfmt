#!/usr/bin/env python3
"""Writes src/swift/unicode_data.ts: one table of Unicode properties for Swift's
Character semantics (grapheme cluster breaks, String.count) and case tests
(Character.isUppercase, uppercased() == self).

Grapheme_Cluster_Break and Extended_Pictographic come from Perl's Unicode::UCD
(perl 5.38: Unicode 15.0); categories, combining classes and case mappings from
Python's unicodedata (Unicode 15.1). SwiftFormat's binary uses a newer Swift
standard library, so a code point that is unassigned in Unicode 15.1, or a virama
(canonical combining class 9, which Indic conjunct breaking (GB9c) depends on), is
marked uncertain: a count or case test that meets one makes the file skip.

Each entry is `start:value` (hex) and holds until the next start; value bits:
  0-3   Grapheme_Cluster_Break (see SW_GCB_* in unicode.ts)
  4     Extended_Pictographic
  5     uncertain
  6     Uppercase   7 Lowercase   8 titlecase letter (Lt)
  9     uppercase mapping differs   10 lowercase mapping differs
"""
import os
import subprocess
import unicodedata

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))

GCB = {"Other": 0, "ExtPict_XX": 0, "CR": 1, "LF": 2, "Control": 3, "Extend": 4, "ZWJ": 5,
       "Regional_Indicator": 6, "Prepend": 7, "SpacingMark": 8, "L": 9, "V": 10, "T": 11,
       "LV": 12, "LVT": 13}

perl = r'''
use Unicode::UCD qw(prop_invmap prop_invlist);
my ($l, $m) = prop_invmap("GCB");
print "G ", join(" ", map { "$l->[$_]=$m->[$_]" } 0 .. $#$l), "\n";
my @e = prop_invlist("Extended_Pictographic");
print "E ", join(" ", @e), "\n";
'''
out = subprocess.run(["perl", "-e", perl], capture_output=True, text=True, check=True).stdout
gcb_starts, gcb_vals, ep = [], [], []
for line in out.splitlines():
    if line.startswith("G "):
        for item in line[2:].split():
            s, v = item.split("=")
            gcb_starts.append(int(s))
            gcb_vals.append(GCB[v])
    elif line.startswith("E "):
        ep = [int(x) for x in line[2:].split()]

N = 0x110000
vals = [0] * N
for k, s in enumerate(gcb_starts):
    e = gcb_starts[k + 1] if k + 1 < len(gcb_starts) else N
    for cp in range(s, e):
        vals[cp] = gcb_vals[k]
for k in range(0, len(ep), 2):
    e = ep[k + 1] if k + 1 < len(ep) else N
    for cp in range(ep[k], e):
        vals[cp] |= 1 << 4
for cp in range(N):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    cat = unicodedata.category(c)
    v = vals[cp]
    if cat == "Cn" or unicodedata.combining(c) == 9:
        v |= 1 << 5
    if c.isupper():
        v |= 1 << 6
    if c.islower():
        v |= 1 << 7
    if cat == "Lt":
        v |= 1 << 8
    if c.upper() != c:
        v |= 1 << 9
    if c.lower() != c:
        v |= 1 << 10
    vals[cp] = v

entries = []
prev = None
for cp in range(N):
    if vals[cp] != prev:
        entries.append("%x:%x" % (cp, vals[cp]))
        prev = vals[cp]

text = ",".join(entries)
chunks = [text[i:i + 100] for i in range(0, len(text), 100)]
lines = [
    "// Generated by tools/swift/gen_unicode.py: Unicode properties for Swift's Character",
    "// semantics (Unicode 15.0 grapheme breaks, 15.1 case data). Do not edit.",
    "",
    "export const SW_UNI_ENTRIES: i32 = %d;" % len(entries),
    "",
    "export const SW_UNI_TABLE: string =",
]
for k, ch in enumerate(chunks):
    lines.append('  "%s"%s' % (ch, " +" if k + 1 < len(chunks) else ";"))
open(os.path.join(root, "src", "swift", "unicode_data.ts"), "w").write("\n".join(lines) + "\n")
print("entries:", len(entries), "bytes:", len(text))
