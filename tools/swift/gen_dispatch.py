#!/usr/bin/env python3
"""Writes src/swift/dispatch.ts from tools/swift/rules.txt.

Each line of rules.txt is `ruleName module function` (the rule's port: a
function `(f: SwFormatter) => void`), `ruleName module function bool` (one that
answers false when it cannot handle the file), or `ruleName noop reason` (a
rule that cannot change anything with the default options).
"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
rules = []
for line in open(os.path.join(here, "rules.txt")):
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    rules.append(line.split(None, 3))


def const(name):
    return "SW_RULE_" + re.sub(r"([A-Z])", r"_\1", name).upper()


imports = {}
for r in rules:
    if r[1] != "noop":
        imports.setdefault(r[1], []).append(r[2])

out = []
out.append("// Runs one rule by id. A rule not ported yet answers false (the file is")
out.append("// skipped). Generated by tools/swift/gen_dispatch.py from tools/swift/rules.txt.")
out.append("//")
out.append("// Ported from SwiftFormat 0.64.7 (MIT License, Copyright (c) 2016 Nick")
out.append("// Lockwood).")
out.append("")
out.append('import { SwFormatter } from "./formatter";')
out.append("import {")
for c in sorted(const(r[0]) for r in rules):
    out.append("  %s," % c)
out.append('} from "./rules";')
for mod in sorted(imports):
    out.append("import {")
    for fn in sorted(set(imports[mod])):
        out.append("  %s," % fn)
    out.append('} from "./%s";' % mod)
out.append("")
out.append("/** Applies rule `r`; answers false when the rule is not ported or cannot handle the file. */")
out.append("export const swRunRule = (f: SwFormatter, r: i32): boolean => {")
out.append("  switch (r) {")
for r in rules:
    out.append("    case %s:" % const(r[0]))
    if r[1] == "noop":
        out.append("      // %s" % " ".join(r[2:]))
        out.append("      return true;")
    elif len(r) > 3 and r[3] == "bool":
        out.append("      return %s(f);" % r[2])
    else:
        out.append("      %s(f);" % r[2])
        out.append("      return true;")
out.append("    default:")
out.append("      return false;")
out.append("  }")
out.append("};")
open(os.path.join(root, "src", "swift", "dispatch.ts"), "w").write("\n".join(out) + "\n")
