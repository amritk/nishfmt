"""Regenerates src/rust/uident_table.ts: the character classes rustc_lexer
1.99.1 lexes identifiers by.

    python3 -I tools/rust/uident/mk.py <unicode-ident-1.0.24> <unicode-properties-0.1.4> <rust-1.99.1>

The first two are the crates' sources, extracted from
https://static.crates.io/crates/<name>/<name>-<version>.crate, the third
the Rust 1.99.1 source tree (tools/rust/NOTES.md fetches it). The script
reads them as data:

- unicode-ident's tries (src/tables.rs), evaluated for every code point as
  its src/lib.rs does: bit 1 XID_Start, bit 2 XID_Continue (Unicode 17.0);
- unicode-properties' EMOJI_STATUS table: bit 4 `is_emoji_char`;
- rustc_parse's UNICODE_ARRAY (src/lexer/unicode_chars.rs), the
  confusables an invalid identifier may not consist of: bit 8.

It writes the runs of code points with the same bits.
"""

import os
import re
import sys

src = open(os.path.join(sys.argv[1], "src", "tables.rs"), encoding="utf-8").read()
props = open(os.path.join(sys.argv[2], "src", "tables.rs"), encoding="utf-8").read()
uchars = open(
    os.path.join(sys.argv[3], "compiler", "rustc_parse", "src", "lexer", "unicode_chars.rs"), encoding="utf-8"
).read()
lib = open(os.path.join(sys.argv[1], "src", "lib.rs"), encoding="utf-8").read()

assert "pub const UNICODE_VERSION: (u8, u8, u8) = (17, 0, 0);" in src
assert "pub(crate) const CHUNK: usize = 64;" in src
# The lookups this script evaluates.
for fn in ("is_xid_start", "is_xid_continue"):
    body = re.search(r"pub fn " + fn + r"\(ch: char\) -> bool \{(.*?)\n\}", lib, re.S).group(1)
    assert "ch as usize / 8 / CHUNK" in body and "chunk as usize * CHUNK / 2 + ch as usize / 8 % CHUNK" in body
    assert "wrapping_shr(ch as u32 % 8) & 1 != 0" in body


def static_bytes(name):
    body = re.search(r"static " + name + r"\b[^=]*=(.*?);\n", src, re.S).group(1)
    return [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", body)]


def u128_const(name):
    return int(re.search(r"const " + name + r": u128 = 0x([0-9a-f]+);", src).group(1), 16)


TRIE_START = static_bytes("TRIE_START")
TRIE_CONTINUE = static_bytes("TRIE_CONTINUE")
LEAF = static_bytes("LEAF")
ASCII_START = u128_const("ASCII_START")
ASCII_CONTINUE = u128_const("ASCII_CONTINUE")
assert len(TRIE_START) == 411 and len(TRIE_CONTINUE) == 1793 and len(LEAF) == 7808


def lookup(trie, ascii_bits, cp):
    if cp < 128:
        return (ascii_bits >> cp) & 1 == 1
    i = cp // 8 // 64
    chunk = trie[i] if i < len(trie) else 0
    offset = chunk * 64 // 2 + cp // 8 % 64
    return (LEAF[offset] >> (cp % 8)) & 1 == 1


# is_emoji_status_for_emoji_char: every status but NonEmoji and NonEmojiButEmojiComponent.
assert "!matches!(s, EmojiStatus::NonEmoji | EmojiStatus::NonEmojiButEmojiComponent)" in props
table = re.search(r"const EMOJI_STATUS: &\[\(char, char, EmojiStatus\)\] = &\[(.*?)\];", props, re.S).group(1)
EMOJI = []
for lo, hi, st in re.findall(r"\('\\u\{([0-9a-f]+)\}', '\\u\{([0-9a-f]+)\}',\s*EmojiStatus::(\w+)\)", table):
    if st not in ("NonEmoji", "NonEmojiButEmojiComponent"):
        EMOJI.append((int(lo, 16), int(hi, 16)))
assert len(EMOJI) > 100

arr = re.search(r"pub\(super\) static UNICODE_ARRAY: &\[\(char, &str, &str\)\] = &\[(.*?)\n\];", uchars, re.S).group(1)
CONFUSABLE = set()
for line in arr.split("\n"):
    m = re.match(r"\s*\('(.+?)', \"", line)
    if m:
        ch = m.group(1)
        if ch.startswith("\\u{"):
            ch = chr(int(ch[3:-1], 16))
        assert len(ch) == 1, line
        CONFUSABLE.add(ord(ch))
assert len(CONFUSABLE) > 250, len(CONFUSABLE)

runs = []
prev = -1
for cp in range(0x110000):
    v = 0
    if not 0xD800 <= cp <= 0xDFFF:
        v = (1 if lookup(TRIE_START, ASCII_START, cp) else 0) | (2 if lookup(TRIE_CONTINUE, ASCII_CONTINUE, cp) else 0)
        if any(a <= cp <= b for a, b in EMOJI):
            v |= 4
        if cp in CONFUSABLE:
            v |= 8
    if v != prev:
        runs.append("%06x%x" % (cp, v))
        prev = v

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "src", "rust", "uident_table.ts")
with open(out, "w") as f:
    f.write("// Generated by tools/rust/uident/mk.py from unicode-ident 1.0.24 ((MIT OR\n")
    f.write("// Apache-2.0) AND Unicode-3.0, Copyright David Tolnay), unicode-properties\n")
    f.write("// 0.1.4 (MIT OR Apache-2.0, Copyright The Rust Project Developers) and\n")
    f.write("// rustc_parse 1.99.1 (MIT OR Apache-2.0, Copyright The Rust Project\n")
    f.write("// Developers); do not edit.\n")
    f.write("//\n")
    f.write("// Runs of code points: 6 hex digits of the run's first code point, then\n")
    f.write("// one: 1 XID_Start | 2 XID_Continue | 4 emoji | 8 confusable (lexer.ts).\n\n")
    f.write("export const RS_UIDENT_NRUNS: i32 = %d;\n\n" % len(runs))
    f.write("export const RS_UIDENT_RUNS: string =\n")
    for i in range(0, len(runs), 10):
        end = ";\n" if i + 10 >= len(runs) else " +\n"
        f.write('  "' + "".join(runs[i : i + 10]) + '"' + end)
print("uident_table.ts: %d runs" % len(runs))
