#!/usr/bin/env python3
"""Generate src/ruby/team.ts: one field per cop class in src/ruby/cops/, run
and merged in RuboCop's registry order (coporder.txt, from RuboCop 1.92.2's
registry with the default configuration).

    python3 genteam.py
"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
cops_dir = os.path.join(here, "../../src/ruby/cops")
order = [l.strip() for l in open(os.path.join(here, "coporder.txt")) if l.strip()]
rank = {n: i for i, n in enumerate(order)}

cops = []
for f in sorted(os.listdir(cops_dir)):
    if not f.endswith(".ts"):
        continue
    src = open(os.path.join(cops_dir, f)).read()
    # Each exported Cop class, with the name its constructor gives its RbCop.
    for m in re.finditer(r"export class (Cop\w+) \{(.*?)(?=\nexport |\Z)", src, re.S):
        cls = m.group(1)
        nm = re.search(r'this\.c = new RbCop\("([\w/]+)"\)', m.group(2))
        if not nm:
            continue
        name = nm.group(1)
        if name not in rank:
            raise SystemExit(f"{name} is not in the registry order")
        cops.append((rank[name], name, cls, f[:-3]))
cops.sort()

def field(cls):
    return cls[3].lower() + cls[4:]

out = ['''// RuboCop::Cop::Team for `rubocop -a`: every cop inspects the source, and
// their correctors merge in registry order, skipping a cop whose corrections
// clobber an earlier one's or that is autocorrect-incompatible with a cop
// already merged. Generated by tools/ruby/genteam.py.
//
// Ported from RuboCop 1.92.2 (MIT License, Copyright (c) 2012-24 Bozhidar
// Batsov).
''', 'import { RbCop } from "./cop";']
for _, _, cls, mod in sorted(cops, key=lambda c: c[3]):
    out.append(f'import {{ {cls} }} from "./cops/{mod}";')
out.append('import { rbIncompatible } from "./registry";')
out.append('import { RbRewriter } from "./rewriter";')
out.append('import { RbSource } from "./source";')
out.append('')
out.append('export class RbTeam {')
for _, _, cls, _ in cops:
    out.append(f'  {field(cls)}: {cls};')
out.append('  // The cops\' shared state, in registry order.')
out.append('  cops: RbCop[];')
out.append('  // FFRBONLY: run only these cops (comma-separated names).')
out.append('  only: string = "";')
out.append('')
out.append('  constructor() {')
for _, _, cls, _ in cops:
    out.append(f'    this.{field(cls)} = new {cls}();')
out.append('    this.cops = [' + ', '.join(f'this.{field(c[2])}.c' for c in cops) + '];')
out.append('  }')
out.append('''
  private on(name: string): boolean {
    if (this.only.length === 0) {
      return true;
    }
    return `,${this.only},`.indexOf(`,${name},`) >= 0;
  }

  /** One pass: the merged corrections, or null when no cop corrects anything. */
  run(src: RbSource): RbRewriter | null {''')
for _, name, cls, _ in cops:
    f = field(cls)
    out.append(f'    if (this.on("{name}")) {{\n      this.{f}.run(src);\n    }} else {{\n      this.{f}.c.begin(src);\n    }}')
out.append('''    const merged = new RbRewriter(src.n);
    const applied: string[] = [];
    for (const c of this.cops) {
      if (c.rw.empty()) {
        continue;
      }
      let skip = false;
      for (const o of applied) {
        if (rbIncompatible(c.name, o)) {
          skip = true;
        }
      }
      if (skip) {
        continue;
      }
      merged.merge(c.rw);
      applied.push(c.name);
    }
    return merged.empty() ? null : merged;
  }
}
''')
open(os.path.join(here, "../../src/ruby/team.ts"), "w").write("\n".join(out))
print(f"{len(cops)} cops")
