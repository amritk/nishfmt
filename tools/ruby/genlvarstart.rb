# Generate src/ruby/cops/lint_lvar_start_table.ts: the non-ASCII code points
# that cannot start a local variable name by RuboCop 1.92.3's
# VariableForce::LOCAL_VARIABLE_NAME (an upper or titlecase letter), as
# ranges, read from the Ruby that runs RuboCop:
#
#     ruby tools/ruby/genlvarstart.rb > src/ruby/cops/lint_lvar_start_table.ts
#     npx biome format --write src/ruby/cops/lint_lvar_start_table.ts
re = /\A(?![[:upper:]\p{Lt}])[a-z_\P{ASCII}]\z/
ranges = []
start = nil
(0x80..0x110000).each do |c|
  bad = c < 0x110000 && !(0xD800..0xDFFF).cover?(c) && !re.match?([c].pack("U"))
  if bad
    start ||= c
  elsif start
    ranges << (start == c - 1 ? start.to_s(16) : "#{start.to_s(16)}-#{(c - 1).to_s(16)}")
    start = nil
  end
end

puts <<~TS
  // Generated by tools/ruby/genlvarstart.rb from Ruby #{RUBY_VERSION} (Unicode
  // #{RbConfig::CONFIG["UNICODE_VERSION"]}): the non-ASCII code points that cannot start a
  // local variable name, by RuboCop 1.92.3's VariableForce::LOCAL_VARIABLE_NAME
  // (MIT License, Copyright (c) 2012-24 Bozhidar Batsov). Hex ranges, comma
  // separated. Do not edit.

  export const LVAR_BAD_START: string =
    "#{ranges.join(",")}";
TS
