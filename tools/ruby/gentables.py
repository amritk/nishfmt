# Generates src/ruby/tables.ts: the parser gem's Ragel lexer tables and racc
# parser tables, each as a string constant of 3 characters per entry.
import re, sys
G = '/opt/rbenv/versions/3.3.6/lib/ruby/gems/3.3.0/gems/parser-3.3.13.0/lib/parser'
OUT = sys.argv[1]
BASE = 40          # first character of the 64-character alphabet
OFF = 131072       # added to every value (negatives fit)
NIL = 262143       # racc's nil

def arr(src, name):
    m = re.search(r'(?:self\.)?' + re.escape(name) + r' = \[\s*(.*?)\]', src, re.S)
    if not m: raise SystemExit('missing ' + name)
    vals = []
    for t in m.group(1).replace('\n', ' ').split(','):
        t = t.strip()
        if not t: continue
        vals.append(None if t == 'nil' else int(t))
    return vals

def enc(vals):
    out = []
    for v in vals:
        x = NIL if v is None else v + OFF
        assert 0 <= x <= NIL, v
        for sh in (12, 6, 0):
            c = BASE + ((x >> sh) & 63)
            out.append('\\\\' if c == 92 else chr(c))
    return ''.join(out)

lines = ['// Generated by gentables.py from the parser gem 3.3.13.0 (MIT License,',
         '// Copyright (c) 2013-2024 parser contributors): its Ragel lexer tables and',
         '// racc parser tables, 3 characters per entry (see rbAt). Do not edit.', '']
TABLES = []
def emit(name, vals):
    lines.append(f'export const {name}: string = "{enc(vals)}";')
    lines.append(f'export const {name}_N: i32 = {len(vals)};')
    TABLES.append(name)

f1 = open(G + '/lexer-F1.rb').read()
for n in ['_lex_trans_keys', '_lex_key_spans', '_lex_index_offsets', '_lex_indicies', '_lex_trans_targs',
          '_lex_trans_actions', '_lex_to_state_actions', '_lex_from_state_actions', '_lex_eof_trans']:
    emit('RL' + n.upper(), arr(f1, n))
for m in re.finditer(r'self\.(lex_[a-z_]+) = (\d+);', f1):
    lines.append(f'export const RL_{m.group(1).upper()}: i32 = {m.group(2)};')
st = open(G + '/lexer-strings.rb').read()
for n in ['_lex_actions', '_lex_trans_keys', '_lex_key_spans', '_lex_index_offsets', '_lex_indicies', '_lex_trans_targs',
          '_lex_trans_actions', '_lex_to_state_actions', '_lex_from_state_actions', '_lex_eof_trans']:
    emit('RS' + n.upper(), arr(st, n))
for m in re.finditer(r'self\.(lex_[a-z_]+) = (\d+);', st):
    lines.append(f'export const RS_{m.group(1).upper()}: i32 = {m.group(2)};')
py = open(G + '/ruby33.rb').read()
for n in ['racc_action_table', 'racc_action_check', 'racc_action_pointer', 'racc_action_default',
          'racc_goto_table', 'racc_goto_check', 'racc_goto_pointer', 'racc_goto_default']:
    emit('RP_' + n[5:].upper(), arr(py, n))
m = re.search(r'racc_reduce_table = \[\s*(.*?)\]', py, re.S)
items = [t.strip() for t in m.group(1).replace('\n', ' ').split(',') if t.strip()]
rlen, rnt, ract = [], [], []
for i in range(0, len(items), 3):
    rlen.append(int(items[i])); rnt.append(int(items[i + 1]))
    a = items[i + 2]
    ract.append(int(a[len(':_reduce_'):]) if a.startswith(':_reduce_') and a != ':_reduce_none' else (-1 if a == ':_reduce_none' else -2))
emit('RP_REDUCE_LEN', rlen); emit('RP_REDUCE_NT', rnt); emit('RP_REDUCE_ACT', ract)
for k in ['racc_nt_base', 'racc_shift_n', 'racc_reduce_n']:
    lines.append(f'export const RP_{k[5:].upper()}: i32 = {re.search(k + r" = (\d+)", py).group(1)};')
tt = re.search(r'racc_token_table = \{(.*?)\}', py, re.S).group(1)
names = []
for mm in re.finditer(r'(:?"?[A-Za-z_][A-Za-z0-9_]*"?|false|"[^"]*"|:"[^"]*") => (\d+)', tt):
    k, v = mm.group(1), int(mm.group(2))
    k = k.lstrip(':').strip('"')
    if re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', k) and k not in ('false', 'error'):
        lines.append(f'export const TK_{k}: i32 = {v};')
    names.append((v, k))
lines.append('')
lines.append('/** Entry `i` of a table string. */')
lines.append('export const rbAt = (t: string, i: i32): i32 => {')
lines.append('  const k = i * 3;')
lines.append(f'  const x = ((t.charCodeAt(k) - {BASE}) << 12) | ((t.charCodeAt(k + 1) - {BASE}) << 6) | (t.charCodeAt(k + 2) - {BASE});')
lines.append(f'  return x === {NIL} ? RB_NIL : x - {OFF};')
lines.append('};')
lines.append('')
lines.append('/** racc\'s nil. */')
lines.append('export const RB_NIL: i32 = -2147483647;')
lines.append('')
lines.append('// The tables decoded once per process into module storage, read as `T_D[i]`.')
for t in TABLES:
    lines.append(f'export const {t}_D = new Int32Array({t}_N);')
lines.append('const RB_TABLES_READY = new Int32Array(1);')
lines.append('')
lines.append('/** Decodes every table on the first call. */')
lines.append('export const rbTablesInit = (): void => {')
lines.append('  if (RB_TABLES_READY[0] === 1) {')
lines.append('    return;')
lines.append('  }')
for t in TABLES:
    lines.append(f'  for (let i = 0; i < {t}_N; i++) {{')
    lines.append(f'    {t}_D[i] = rbAt({t}, i);')
    lines.append('  }')
lines.append('  RB_TABLES_READY[0] = 1;')
lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('tokens', len(names), 'reduce', len(rlen))
