# Generate src/ruby/cops/lint_exception_table.ts: the exception classes
# Lint/ShadowedException can resolve. That cop evaluates each rescued
# exception's source with `Kernel.const_get` inside the RuboCop process, so
# what it knows is whatever that process has loaded while it inspects a file.
# This loads RuboCop, runs the cop once (as rdet.sh's oracle does: --only,
# --format json, no cache) to pull in what a run loads lazily, then lists
# every constant path that names an Exception subclass.
#
#     ruby tools/ruby/genexceptions.rb
require "rubocop"
require "stringio"
require "tmpdir"

Dir.mktmpdir do |dir|
  File.write(File.join(dir, "a.rb"), "begin\n  x\nrescue Exception, StandardError\nend\n")
  File.write(File.join(dir, "rubocop.yml"), "AllCops:\n  TargetRubyVersion: 3.3\n  NewCops: disable\n  SuggestExtensions: false\n")
  out = $stdout
  $stdout = StringIO.new
  RuboCop::CLI.new.run(["--cache", "false", "-c", File.join(dir, "rubocop.yml"), "--only",
                        "Lint/ShadowedException", "--format", "json", File.join(dir, "a.rb")])
  $stdout = out
end

name_of = Module.instance_method(:name)
paths = {}
2.times do
  ObjectSpace.each_object(Module) do |m|
    mn = name_of.bind_call(m)
    next unless mn && !mn.start_with?("#")
    m.constants(false).each do |c|
      next if m.autoload?(c)
      v = begin
        m.const_get(c, false)
      rescue StandardError, LoadError
        next
      end
      next unless v.is_a?(Class) && v <= Exception
      paths[m == Object ? c.to_s : "#{mn}::#{c}"] = v
    end
  end
end

classes = paths.values.uniq.sort_by { |c| name_of.bind_call(c).to_s }
index = classes.each_with_index.to_h
rows = classes.map do |c|
  sup = c == Exception ? -1 : index.fetch(c.superclass)
  errno = c.ancestors[1] == SystemCallError && c.const_defined?(:Errno) ? c.const_get(:Errno) : -1
  "#{sup} #{errno}"
end
aliases = paths.sort.map { |p, c| "#{p} #{index[c]}" }

ts = <<~TS
  // The exception classes Lint/ShadowedException resolves with Kernel.const_get
  // in RuboCop 1.92.2's process (Ruby 3.3.6): each class's superclass and Errno
  // value, and every constant path that names one. Generated by
  // tools/ruby/genexceptions.rb.
  //
  // Ported from RuboCop 1.92.2 (MIT License, Copyright (c) 2012-24 Bozhidar
  // Batsov).

  // One row per class, by index: "superclass_index errno" (-1: none).
  export const LEX_CLASSES: string = "#{rows.join(";")}";

  // "path index" per constant path, `;`-separated.
  export const LEX_PATHS: string = "#{aliases.join(";")}";
TS
File.write(File.expand_path("../../src/ruby/cops/lint_exception_table.ts", __dir__), ts)
puts "#{classes.size} classes, #{aliases.size} paths"
