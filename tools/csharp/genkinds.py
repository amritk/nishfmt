#!/usr/bin/env python3
# Generates src/csharp/kinds.ts from Roslyn's SyntaxKind.cs, SyntaxKindFacts.cs
# and Syntax.xml: every SyntaxKind as K_<Name> (Roslyn's own numbers), every
# syntax type as Y_<Name>, the slot layout of each concrete type (the fields
# of Syntax.xml in order) as F_<Type>_<Field>, and the tables the parser and
# printers read (kind -> type, type -> base type, type -> slot shape, kind ->
# text).
#
#   genkinds.py <roslyn>/src/Compilers/CSharp/Portable/Syntax > src/csharp/kinds.ts
import re
import sys
import xml.etree.ElementTree as ET

d = sys.argv[1]
enum = open(d + "/SyntaxKind.cs", encoding="utf-8-sig").read()
kinds = []
for m in re.finditer(r"^\s*(\w+)\s*=\s*(\d+)\s*,", enum, re.M):
    kinds.append((m.group(1), int(m.group(2))))
facts = open(d + "/SyntaxKindFacts.cs", encoding="utf-8-sig").read()
gt = facts[facts.index("public static string GetText(SyntaxKind kind)"):]
gt = gt[: gt.index("default:")]
texts = {}
pending = []
for line in gt.splitlines():
    m = re.match(r"\s*case SyntaxKind\.(\w+):", line)
    if m:
        pending.append(m.group(1))
        continue
    m = re.match(r'\s*return "((?:[^"\\]|\\.)*)";', line)
    if m:
        for p in pending:
            texts[p] = m.group(1)
        pending = []

root = ET.parse(d + "/Syntax.xml").getroot()
types = {}
order = []


def fields_of(el, optional, out):
    for f in el:
        if f.tag == "Field":
            out.append((f.get("Name"), f.get("Type"), optional or f.get("Optional") == "true"))
        elif f.tag == "Choice":
            fields_of(f, True, out)
        elif f.tag == "Sequence":
            fields_of(f, optional, out)


for n in root:
    if n.tag not in ("Node", "AbstractNode"):
        continue
    name = n.get("Name")
    assert name.endswith("Syntax"), name
    short = name[: -len("Syntax")]
    fs = []
    fields_of(n, False, fs)
    types[short] = {
        "base": n.get("Base"),
        "abstract": n.tag == "AbstractNode",
        "kinds": [k.get("Name") for k in n.findall("Kind")],
        "fields": fs,
    }
    order.append(short)


def shape(t):
    if t == "SyntaxToken":
        return "t"
    if t.startswith("SyntaxList<SyntaxToken>") or t == "SyntaxList<SyntaxToken>":
        return "k"
    if t.startswith("SyntaxList<"):
        return "l"
    if t.startswith("SeparatedSyntaxList<"):
        return "s"
    return "n"


out = []
w = out.append
w("// Generated by tools/csharp/genkinds.py from Roslyn's SyntaxKind.cs, SyntaxKindFacts.cs and")
w("// Syntax.xml (MIT License, Copyright the .NET Foundation and Contributors). Do not edit.")
w("")
for name, v in kinds:
    w(f"export const K_{name}: i32 = {v};")
w("")
yid = {}
for i, t in enumerate(order):
    yid[t] = i + 1
    w(f"export const Y_{t}: i32 = {i + 1};")
w("")
for t in order:
    if types[t]["abstract"]:
        continue
    for i, (fname, ftype, opt) in enumerate(types[t]["fields"]):
        w(f"export const F_{t}_{fname}: i32 = {i};")
w("")
w("/** The syntax type of a node kind, or 0 for a kind that is not a node. */")
w("export const csKindType = (k: i32): i32 => {")
w("  switch (k) {")
for t in order:
    for k in types[t]["kinds"]:
        w(f"    case K_{k}:")
        w(f"      return Y_{t};")
w("    default:")
w("      return 0;")
w("  }")
w("};")
w("")
w("/** The base type of a syntax type, or 0 for CSharpSyntaxNode. */")
w("export const csTypeBase = (y: i32): i32 => {")
w("  switch (y) {")
for t in order:
    b = types[t]["base"]
    bs = b[: -len("Syntax")] if b.endswith("Syntax") else b
    if bs in yid:
        w(f"    case Y_{t}:")
        w(f"      return Y_{bs};")
w("    default:")
w("      return 0;")
w("  }")
w("};")
w("")
w("/** The slots of a concrete type: n node, t token, l node list, s separated list, k token list; upper case is optional. */")
w("export const csTypeShape = (y: i32): string => {")
w("  switch (y) {")
for t in order:
    if types[t]["abstract"]:
        continue
    s = "".join(shape(ft).upper() if opt else shape(ft) for (_, ft, opt) in types[t]["fields"])
    w(f"    case Y_{t}:")
    w(f'      return "{s}";')
w("    default:")
w('      return "";')
w("  }")
w("};")
w("")
w("/** The fixed text of a token or keyword kind, or the empty string. */")
w("export const csKindText = (k: i32): string => {")
w("  switch (k) {")
for name, v in kinds:
    if name in texts:
        w(f"    case K_{name}:")
        w(f'      return "{texts[name]}";')
w("    default:")
w('      return "";')
w("  }")
w("};")
kv = dict(kinds)
kw = {}
for name, v in kinds:
    if name in texts and (8304 <= v <= 8384 or 8405 <= v <= 8454):
        kw[texts[name]] = (name, v >= 8405)
w("")
w("/** The keyword spelled by s[a, a + n): its kind, the negated kind of a contextual keyword, or 0. */")
w("export const csKeyword = (s: u8[], a: i32, n: i32): i32 => {")
w("  const c0 = toI32(s[a]);")
w("  switch (n) {")
bylen = {}
for t in kw:
    bylen.setdefault(len(t), []).append(t)
for ln in sorted(bylen):
    w(f"    case {ln}:")
    byfirst = {}
    for t in bylen[ln]:
        byfirst.setdefault(t[0], []).append(t)
    for c in sorted(byfirst):
        w(f"      if (c0 === {ord(c)}) {{")
        for t in sorted(byfirst[c]):
            cond = " && ".join(f"toI32(s[a + {i}]) === {ord(ch)}" for i, ch in enumerate(t) if i > 0) or "true"
            name, ctx = kw[t]
            w(f"        if ({cond}) {{")
            w(f"          return {'-' if ctx else ''}K_{name};")
            w("        }")
        w("      }")
    w("      return 0;")
w("    default:")
w("      return 0;")
w("  }")
w("};")
print("\n".join(out))
